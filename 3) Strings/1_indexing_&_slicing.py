# # Sring Slicing 
text = "DataAnalysis"

print (text [:5]) #part of string retrived is "DataA"
print (text [0:4]) #part of string retrived is "Data"
print (text [-4:-1]) #part of string retrived is "ysi"
print (text [5:]) #part of string retrived is "nalysis"
print (text [-3:]) #part of string retrived is "sis"
print (text [:: -1]) # string is reversed 
print (text [4:: -1]) # charcters of sring are reversed from index 0 to 4 i.e "AataD"
